import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const appRoot = resolve(import.meta.dirname, "..");
const repoRoot = resolve(appRoot, "..", "..");
const backendRoot = resolve(repoRoot, "engine", "runtime-core");
const manifest = resolve(backendRoot, "Cargo.toml");

// The native-first pilot is not the existing VMware release product. The
// current bundle still contains VMware guest scripts and a Guest Agent and
// reuses the old installed identity/data directory. Refuse packaging BEFORE
// building sidecars, staging guest binaries or touching installer resources.
// Unblocking requires an explicit migration/release review in source, not an
// operator environment variable or a temporary CLI bypass.
// This native feasibility UI must never inherit the old VMware NSIS payload.
// An explicit release hold cannot be bypassed by renaming a Svelte component.
// A reviewed native distribution contract is required before revisiting this.
const LEGACY_PACKAGE_RELEASE_APPROVED = false;
if (!LEGACY_PACKAGE_RELEASE_APPROVED) {
  throw new Error(
    "PACKAGE_BLOCKED_NATIVE_FEASIBILITY: native feasibility cannot be " +
    "packaged with VMware Guest Agent resources and legacy app identity. " +
    "A separately reviewed native prototype package is required."
  );
}
// A direct packaging command must not silently resolve uncommitted desktop
// dependencies. The canonical G0 source route enforces the same prerequisite.
if (!existsSync(resolve(appRoot, "src-tauri", "Cargo.lock"))) {
  throw new Error("G0 requires src-tauri/Cargo.lock generated by Cargo and committed to Local; refusing a non-reproducible Tauri package.");
}
const binaries = resolve(appRoot, "src-tauri", "binaries");
const guestResources = resolve(appRoot, "src-tauri", "package-resources", "guest", "windows");
const appPackage = JSON.parse(readFileSync(resolve(appRoot, "package.json"), "utf8"));
const packageContract = JSON.parse(readFileSync(resolve(repoRoot, "engine", "distribution", "package-contract.json"), "utf8"));
const tauriBase = JSON.parse(readFileSync(resolve(appRoot, "src-tauri", "tauri.conf.json"), "utf8"));
const tauriPackage = JSON.parse(readFileSync(resolve(appRoot, "src-tauri", "tauri.package.conf.json"), "utf8"));
if (packageContract.schema !== 1 || !Array.isArray(packageContract.requiredFiles)) {
  throw new Error("Unsupported or invalid Virtual Clients package contract.");
}
// The configured resource destination alone does not prove that the mapped
// source file exists. Resolve every required payload through the actual Tauri
// origin -> destination mapping before starting a potentially expensive build.
const tauriRoot = resolve(appRoot, "src-tauri");
const resourceRoutes = [
  ...Object.entries(tauriBase.bundle?.resources ?? {}),
  ...Object.entries(tauriPackage.bundle?.resources ?? {}),
];
const generatedExecutables = new Set(["m-bedrock-virtual-clients.exe", "virtual-clients.exe"]);
const guestAgentDestination = "guest/windows/virtual-guest-agent.exe";
const guestAgentOrigin = "package-resources/guest/windows/virtual-guest-agent.exe";
for (const requiredFile of packageContract.requiredFiles) {
  if (generatedExecutables.has(requiredFile)) continue;
  if (requiredFile.startsWith("/") || requiredFile.split("/").some((part) => part === ".." || part === "")) {
    throw new Error(`Invalid installed package path: ${requiredFile}`);
  }
  const packaged = resourceRoutes.some(([origin, destination]) => {
    const remainder = destination === requiredFile
      ? ""
      : destination.endsWith("/") && requiredFile.startsWith(destination)
        ? requiredFile.slice(destination.length)
        : null;
    if (remainder === null) return false;
    if (requiredFile === guestAgentDestination) {
      // This artifact is built and staged by this command below, not checked
      // before its build. Require the explicit package resource route.
      return origin === guestAgentOrigin && destination === guestAgentDestination;
    }
    const source = resolve(tauriRoot, origin, remainder);
    return existsSync(source) && statSync(source).isFile();
  });
  if (!packaged) {
    throw new Error(`Tauri package source is missing or unmapped: ${requiredFile}`);
  }
}
const backendCargo = readFileSync(manifest, "utf8");
const backendVersion = /^version\s*=\s*"([^"]+)"\s*$/m.exec(backendCargo)?.[1];
if (!backendVersion || backendVersion !== appPackage.version) {
  throw new Error(`Package/backend version mismatch: desktop=${appPackage.version}, backend=${backendVersion ?? "unknown"}`);
}

const run = (program, args, cwd = appRoot) => {
  const result = spawnSync(program, args, {
    cwd,
    stdio: "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
};

const rustc = spawnSync("rustc", ["-vV"], {
  encoding: "utf8",
});
if (rustc.error) throw rustc.error;
if (rustc.status !== 0) process.exit(rustc.status ?? 1);
const host = /^host:\s*(.+)$/m.exec(rustc.stdout)?.[1]?.trim();
if (!host) throw new Error("Rust host target triple could not be resolved.");
// NSIS desktop, host CLI and Guest Agent must be the same Windows x64 ABI.
// Cross-target packaging is not implemented; fail closed on host mismatch.
if (host !== "x86_64-pc-windows-msvc") {
  throw new Error(`Windows package requires an x86_64-pc-windows-msvc Rust host; observed ${host}. No cross-target packaging is implemented.`);
}

run(
  "cargo",
  [
    "build",
    "--locked",
    "--manifest-path",
    manifest,
    "--release",
    "--bin",
    "virtual-clients",
    "--bin",
    "virtual-guest-agent",
  ],
  repoRoot,
);

mkdirSync(binaries, { recursive: true });
for (const file of readdirSync(binaries)) {
  if (file.startsWith("virtual-clients-")) {
    rmSync(resolve(binaries, file), { force: true });
  }
}

const extension = host.includes("windows") ? ".exe" : "";
const cliSource = resolve(backendRoot, "target", "release", "virtual-clients" + extension);
if (!existsSync(cliSource)) throw new Error(`Required CLI was not built: ${cliSource}`);
const cliDestination = resolve(binaries, `virtual-clients-${host}${extension}`);
copyFileSync(cliSource, cliDestination);
console.log(`Prepared host sidecar: ${cliDestination}`);

const guestSource = resolve(backendRoot, "target", "release", "virtual-guest-agent" + extension);
if (!existsSync(guestSource)) throw new Error(`Required Guest Agent was not built: ${guestSource}`);
mkdirSync(guestResources, { recursive: true });
const guestDestination = resolve(guestResources, "virtual-guest-agent" + extension);
copyFileSync(guestSource, guestDestination);
console.log(`Prepared guest payload: ${guestDestination}`);
